import fs from 'node:fs';
import path from 'node:path';
import openapiTS, { astToString } from 'openapi-typescript';

/** Regenerates src/schema.ts from the running API's Swagger JSON (API_URL, default localhost:4000). */
async function main(): Promise<void> {
  const url = process.env.API_URL ?? 'http://localhost:4000/api/docs-json';
  const ast = await openapiTS(new URL(url));
  const target = path.join(__dirname, '..', 'src', 'schema.ts');
  fs.writeFileSync(
    target,
    `/* Generated by scripts/generate.ts — do not edit. */\n${astToString(ast)}`,
  );
  console.log(`[api-client] wrote ${path.relative(process.cwd(), target)}`);
}

main().catch((error: unknown) => {
  console.error('[api-client] failed:', error);
  process.exit(1);
});
